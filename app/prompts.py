import os

def get_dynamic_project_context() -> str:
    """如果当前目录下存在 TARS.md，则读取并返回作为项目上下文。"""
    tars_md_path = os.path.join(os.getcwd(), "TARS.md")
    if os.path.exists(tars_md_path):
        try:
            with open(tars_md_path, "r", encoding="utf-8") as f:
                content = f.read()
            return f"\n\n<project_context>\n【注意：以下是当前项目专属的强制规则 (TARS.md)，优先级最高】\n{content}\n</project_context>\n"
        except Exception:
            pass
    return ""

